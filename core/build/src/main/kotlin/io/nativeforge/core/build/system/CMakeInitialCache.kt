package io.nativeforge.core.build.system

import java.io.File

/**
 * The initial-cache script (`cmake -C <file>`) that carries NativeForge's own CMake variables.
 *
 * Passing them as `-D` options made CMake warn about every one the project does not read
 * ("Manually-specified variables were not used by the project"). The old way to silence that,
 * `--no-warn-unused-cli`, is deprecated since CMake 4.2, and its replacement `-Wno-unused-cli`
 * is ignored by older CMake releases. Variables set by an initial-cache script are never
 * reported as unused, with any CMake version.
 *
 * Every entry is written with FORCE so it replaces the value cached by an earlier configure,
 * exactly like `-D` does. Values are bracket arguments (`[==[...]==]`), so quotes, `$`,
 * backslashes and `;` reach CMake unchanged.
 */
internal object CMakeInitialCache {

    /** Variables CMake caches as file paths; everything else is a plain string. */
    private val FILE_PATHS = setOf(
        "CMAKE_C_COMPILER", "CMAKE_CXX_COMPILER", "CMAKE_MAKE_PROGRAM",
        "CMAKE_C_COMPILER_LAUNCHER", "CMAKE_CXX_COMPILER_LAUNCHER",
    )
    private val BOOLEANS = setOf("CMAKE_EXPORT_COMPILE_COMMANDS", "NATIVEFORGE")

    private val ENTRY = Regex("""set\(([A-Za-z0-9_.+-]+) \[(=*)\[(.*?)]\2] CACHE \w+ "[^"]*" FORCE\)""", RegexOption.DOT_MATCHES_ALL)

    fun render(definitions: Map<String, String>): String = buildString {
        appendLine("# Generated by NativeForge before every CMake configure. Do not edit: rewritten on every build.")
        definitions.forEach { (name, value) ->
            val type = when (name) {
                in FILE_PATHS -> "FILEPATH"
                in BOOLEANS -> "BOOL"
                else -> "STRING"
            }
            appendLine("set($name ${bracket(value)} CACHE $type \"Set by NativeForge\" FORCE)")
        }
    }

    /** Writes [definitions] to [file] (only when they changed) and returns it. */
    fun write(file: File, definitions: Map<String, String>): File {
        val text = render(definitions)
        file.parentFile?.mkdirs()
        if (!file.isFile || file.readText() != text) file.writeText(text)
        return file
    }

    /** Reads back the variables of a script written by [render]. */
    fun parse(text: String): Map<String, String> =
        ENTRY.findAll(text).associate { it.groupValues[1] to it.groupValues[3] }

    /** A bracket argument whose closing bracket does not occur in [value]. */
    fun bracket(value: String): String {
        var equals = ""
        while ("]$equals]" in value) equals += "="
        return "[$equals[$value]$equals]"
    }
}
