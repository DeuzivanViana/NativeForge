package io.nativeforge.core.build.system

import io.nativeforge.core.build.model.ArtifactKind
import io.nativeforge.core.build.model.BuildRequest
import java.io.File

/**
 * Makes Makefiles and build.ninja files written for desktop Linux build Android programs.
 *
 * Small shell scripts named `gcc`, `g++`, `cc`, `c++`, `clang` and `clang++` are written to
 * `build/.nativeforge/bin` and put first on PATH. Each one runs the real clang and:
 *
 * * puts the bundled libraries' headers first, so they win over a desktop copy of the
 *   same library in the project (a `third-party/raylib` folder, for example);
 * * drops libraries that do not exist on Android (`-lGL`, `-lX11`, `-lpthread`...);
 * * when linking a graphical program, links it as a shared library with the project's
 *   packages, whatever the output is called (`app.elf` works).
 *
 * The scripts only depend on the build request, so they are rewritten on every build.
 */
internal object CompilerWrappers {

    /** Desktop-only libraries: Android has no X11/GL/ALSA, and pthread/rt live in libc. */
    val DESKTOP_ONLY_LIBRARIES = setOf(
        "GL", "GLU", "glut", "GLEW", "glfw", "glfw3", "X11", "Xrandr", "Xi", "Xcursor", "Xinerama", "Xext",
        "Xxf86vm", "Xrender", "Xfixes", "xcb", "wayland-client", "wayland-cursor", "wayland-egl", "xkbcommon",
        "asound", "pulse", "pulse-simple", "pthread", "rt", "gdi32", "winmm", "opengl32", "user32", "kernel32",
    )

    /** Arguments that mean "do not link". */
    private val NO_LINK_FLAGS = listOf("-c", "-S", "-E", "-M", "-MM", "-fsyntax-only")

    private val WRAPPED = mapOf(
        "gcc" to false, "cc" to false, "clang" to false,
        "g++" to true, "c++" to true, "clang++" to true,
    )

    fun directory(request: BuildRequest): File = File(request.project.buildDirectory, ".nativeforge/bin")

    /** Writes the wrapper scripts and returns their folder (to be put first on PATH). */
    fun write(request: BuildRequest): File {
        val dir = directory(request).apply { mkdirs() }
        WRAPPED.forEach { (name, cxx) ->
            val file = File(dir, name)
            val script = script(request, cxx)
            if (!file.isFile || file.readText() != script) file.writeText(script)
            file.setExecutable(true, false)
        }
        return dir
    }

    fun script(request: BuildRequest, cxx: Boolean): String {
        val toolchain = request.toolchain
        val compiler = if (cxx) toolchain.cxxCompiler else toolchain.cCompiler
        val shared = CompilerFlags.artifactKind(request) == ArtifactKind.SHARED_LIBRARY
        // -I (not -isystem) so the bundled headers come before the Makefile's own -I folders.
        val compileFlags = buildList {
            addAll(toolchain.baseCompileFlags())
            if (shared) add("-fPIC")
            add("-DNATIVEFORGE=1")
            add("-DNATIVEFORGE_RUNTIME_${request.project.config.runtime.name}=1")
            request.dependencies.forEach { dep ->
                dep.includeDirectories.forEach { add("-I${it.path}") }
                addAll(dep.compileFlags)
            }
        }
        val linkFlags = CompilerFlags.linkOptions(request) + CompilerFlags.linkLibraries(request)
        val dropped = DESKTOP_ONLY_LIBRARIES.sorted().joinToString("|") { "-l$it" }
        return buildString {
            appendLine("#!/system/bin/sh")
            appendLine("# Generated by NativeForge for desktop-style Makefiles. Do not edit: rewritten on every build.")
            appendLine("link=1")
            appendLine("for a do case \"\$a\" in ${NO_LINK_FLAGS.joinToString("|")}) link=0 ;; esac; done")
            appendLine("for a do")
            appendLine("  shift")
            appendLine("  case \"\$a\" in $dropped) continue ;; esac")
            appendLine("  set -- \"\$@\" \"\$a\"")
            appendLine("done")
            appendLine("if [ \$link = 1 ] && [ \$# -gt 0 ]; then")
            appendLine("  exec ${quote(compiler.path)} ${compileFlags.joinToString(" ", transform = ::quote)} \"\$@\" ${linkFlags.joinToString(" ", transform = ::quote)}")
            appendLine("fi")
            appendLine("exec ${quote(compiler.path)} ${compileFlags.joinToString(" ", transform = ::quote)} \"\$@\"")
        }
    }

    /** Single-quotes a word for POSIX sh. */
    fun quote(word: String): String =
        if (word.isNotEmpty() && word.all { it.isLetterOrDigit() || it in "-_./=+,:@%" }) word
        else "'" + word.replace("'", "'\\''") + "'"
}
