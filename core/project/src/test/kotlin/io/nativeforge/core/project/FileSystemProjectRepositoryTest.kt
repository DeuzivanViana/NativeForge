package io.nativeforge.core.project

import io.nativeforge.core.common.Outcome
import io.nativeforge.core.project.model.ProjectConfig
import io.nativeforge.core.project.model.RuntimeKind
import io.nativeforge.core.project.model.BuildSystemKind
import io.nativeforge.core.project.model.Language
import io.nativeforge.core.project.template.ProjectOptions
import io.nativeforge.core.project.template.ProjectTemplates
import io.nativeforge.core.project.template.TemplateCategory
import io.nativeforge.core.project.template.TemplateSources
import kotlinx.coroutines.runBlocking
import java.io.File
import java.nio.file.Files
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertIs
import kotlin.test.assertTrue

class FileSystemProjectRepositoryTest {

    private val workspace: File = Files.createTempDirectory("nf-workspace").toFile()
    private val repository = FileSystemProjectRepository(workspace)

    @Test
    fun `every template creates a project that can be reopened`() = runBlocking<Unit> {
        ProjectTemplates.all.forEachIndexed { index, template ->
            val name = "Project $index"
            val created = repository.create(name, template)
            assertIs<Outcome.Success<*>>(created)

            val reopened = repository.open(name).getOrNull()!!
            assertEquals(name, reopened.config.name)
            assertTrue(reopened.root.walkTopDown().any { it.extension in setOf("c", "cpp") })
            assertTrue(reopened.root.walkTopDown().none { it.readTextOrEmpty().contains("@PROJECT_NAME@") })
        }
        assertEquals(ProjectTemplates.all.size, repository.listProjects().size)
    }

    @Test
    fun `templates generate sources for every language and build system they offer`() {
        ProjectTemplates.all.forEach { template ->
            template.languages.forEach { language ->
                template.buildSystems.forEach { buildSystem ->
                    val options = ProjectOptions(language = language, buildSystem = buildSystem)
                    val generated = template.generate("demo", options)
                    val extension = if (language == Language.C) ".c" else ".cpp"
                    assertTrue(generated.files.keys.any { it.endsWith(extension) }, "${template.id} $language")
                    assertEquals(language, generated.config.language)
                    assertEquals(buildSystem, generated.config.buildSystem)
                    assertEquals(template.runtime, generated.config.runtime)
                    if (buildSystem == BuildSystemKind.CMAKE) {
                        val cmake = generated.files.getValue("CMakeLists.txt")
                        assertTrue(("CMAKE_" + (if (language == Language.C) "C" else "CXX") + "_STANDARD") in cmake)
                        assertTrue("cmake_minimum_required(VERSION 3.22...4.2)" in cmake, "policies up to CMake 4.2")
                        val target = if (template.runtime.producesSharedLibrary) "add_library(main SHARED" else "add_executable(main"
                        assertTrue(target in cmake, template.id)
                    }
                    if (buildSystem == BuildSystemKind.MAKE) {
                        val makefile = generated.files.getValue("Makefile")
                        assertTrue("\t\$(CC) \$(CFLAGS)" in makefile, "recipes are indented with tabs")
                        assertEquals(TemplateSources.makeArtifact(template.runtime), generated.config.artifactPath)
                    }
                }
            }
        }
    }

    @Test
    fun `template packages are in the bundled index`() {
        // Tests run in the module folder; the index is generated by packages/build-android-libs.sh.
        val index = File("../../app/src/main/assets/packages/index.json").readText()
        val bundled = Regex("\"name\": \"([^\"]+)\"").findAll(index).map { it.groupValues[1] }.toSet()
        assertTrue("sqlite3" in bundled)
        // The bundled index is searched first, so a bundled package named like a Termux package
        // the toolchain or the terminal needs would replace it (bash links Termux's libncursesw.so).
        val termuxBase = setOf("ncurses", "readline", "libandroid-support", "libiconv", "zlib", "openssl", "libc++", "bash")
        assertTrue((bundled intersect termuxBase).isEmpty(), "bundled packages shadow Termux's: ${bundled intersect termuxBase}")
        ProjectTemplates.all.forEach { template ->
            template.requiredPackages.forEach { assertTrue(it in bundled, "${template.id} needs $it") }
        }
    }

    @Test
    fun `sqlite example uses the sqlite3 package in C and C++`() {
        val template = ProjectTemplates.byId("sqlite-todo")!!
        assertEquals(listOf("sqlite3"), template.requiredPackages)
        listOf(Language.C to "src/main.c", Language.CPP to "src/main.cpp").forEach { (language, path) ->
            val generated = template.generate("demo", ProjectOptions(language = language, buildSystem = BuildSystemKind.CMAKE))
            assertTrue("#include <sqlite3.h>" in generated.files.getValue(path), path)
            assertEquals(listOf("sqlite3"), generated.config.packages)
        }
    }

    @Test
    fun `console templates cover ncurses, modules and unit tests in C and C++`() {
        val console = ProjectTemplates.all.filter { it.category == TemplateCategory.CONSOLE }.map { it.id }
        assertEquals(listOf("console", "ncurses-tui", "multi-file", "unit-tests"), console)
        assertEquals(listOf("ncursesw"), ProjectTemplates.byId("ncurses-tui")!!.requiredPackages)
        val expected = mapOf(
            "ncurses-tui" to (setOf("src/main.c") to setOf("src/main.cpp")),
            "multi-file" to (setOf("src/main.c", "src/grades.c", "include/grades.h") to
                setOf("src/main.cpp", "src/gradebook.cpp", "include/gradebook.hpp")),
            "unit-tests" to (setOf("src/main.c", "src/textutil.c", "include/textutil.h", "include/check.h") to
                setOf("src/main.cpp", "src/textutil.cpp", "include/textutil.hpp", "include/check.hpp")),
        )
        expected.forEach { (id, files) ->
            val template = ProjectTemplates.byId(id)!!
            listOf(Language.C to files.first, Language.CPP to files.second).forEach { (language, paths) ->
                val generated = template.generate("demo", ProjectOptions(language = language, buildSystem = BuildSystemKind.SINGLE))
                assertEquals(paths + ".gitignore", generated.files.keys, "$id $language")
                assertTrue(generated.files.values.all { it.isNotBlank() }, "$id $language")
            }
        }
        val tui = ProjectTemplates.byId("ncurses-tui")!!.generate("demo", ProjectOptions(language = Language.C))
        assertTrue("#include <ncurses.h>" in tui.files.getValue("src/main.c"))
        assertEquals(listOf("ncursesw"), tui.config.packages)
    }

    @Test
    fun `voxel sandbox example runs raylib and Box3D in a NativeActivity`() {
        val template = ProjectTemplates.byId("voxel-sandbox")!!
        assertEquals(listOf("raylib", "box3d"), template.requiredPackages)
        assertEquals(RuntimeKind.NATIVE_ACTIVITY, template.runtime)
        assertEquals(listOf(Language.CPP), template.languages)
        val generated = template.generate("Blocks", ProjectOptions(language = Language.CPP, buildSystem = BuildSystemKind.SINGLE))
        val source = generated.files.getValue("src/main.cpp")
        assertTrue("#include <box3d/box3d.h>" in source)
        assertTrue("InitWindow(0, 0, \"Blocks\")" in source)
        // Split into parts that share one header; the built-in build compiles every file in src/.
        val parts = listOf("game.hpp", "world.cpp", "player.cpp", "things.cpp", "ui.cpp")
        for (part in parts) assertTrue("src/$part" in generated.files, part)
        for (part in parts.drop(1) + "main.cpp") assertTrue("#include \"game.hpp\"" in generated.files.getValue("src/$part"), part)
        assertTrue(generated.files.values.none { "@PROJECT_NAME@" in it })
        assertEquals(listOf("raylib", "box3d"), generated.config.packages)
        // Listed right after the other Box3D example in the New project screen.
        val ids = ProjectTemplates.all.map { it.id }
        assertEquals(ids.indexOf("raylib-3d-physics") + 1, ids.indexOf("voxel-sandbox"))
    }

    @Test
    fun `unsupported options fall back to the template defaults`() {
        val sfml = ProjectTemplates.byId("sfml")!!
        val generated = sfml.generate("demo", ProjectOptions(language = Language.C, standard = "c99", buildSystem = BuildSystemKind.NINJA))
        assertEquals(Language.CPP, generated.config.language)
        assertEquals(Language.CPP.defaultStandard, generated.config.standard)
        assertEquals(BuildSystemKind.SINGLE, generated.config.buildSystem)
        assertTrue(generated.files.keys.none { it == "CMakeLists.txt" || it == "Makefile" })
    }

    @Test
    fun `duplicate and invalid names are rejected`() = runBlocking<Unit> {
        val template = ProjectTemplates.all.first()
        assertIs<Outcome.Success<*>>(repository.create("demo", template))
        assertIs<Outcome.Failure>(repository.create("demo", template))
        assertIs<Outcome.Failure>(repository.create("../escape", template))
        assertIs<Outcome.Failure>(repository.create("", template))
    }

    @Test
    fun `config round trips and unknown keys are ignored`() {
        val json = """{"name":"x","runtime":"sdl2","futureField":42}"""
        val config = ProjectJson.decodeFromString(ProjectConfig.serializer(), json)
        assertEquals(RuntimeKind.SDL2, config.runtime)
        assertEquals("io.nativeforge.user.x", config.export.packageId)
    }

    @Test
    fun `default package id is a valid java package`() {
        assertEquals("io.nativeforge.user.my_game", ProjectConfig.defaultPackageId("My Game"))
        assertEquals("io.nativeforge.user.app_3d", ProjectConfig.defaultPackageId("3D"))
        assertEquals("io.nativeforge.user.app", ProjectConfig.defaultPackageId("!!!"))
    }

    private fun File.readTextOrEmpty() = if (isFile) readText() else ""
}
